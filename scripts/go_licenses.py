#!/usr/bin/env python3
"""Write the licence notices of the Go modules linked into each binary.

For every command in TARGETS the script builds the binary, reads the module
list Go records in it (`go version -m`), finds each module's licence and
notice files in the module cache, and writes one file per binary under
third_party/licenses/. The Go standard library's licence is included too.

    python3 scripts/go_licenses.py          # (re)write the files
    python3 scripts/go_licenses.py --check  # exit 1 if a file is out of date

The output lists modules in sorted order and contains no timestamps, so it
only changes when dependencies change.
"""

import json
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "third_party", "licenses")
TARGETS = {"weft": "./cmd/weft", "agentshield": "./cmd/agentshield"}
LICENSE_RE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|PATENTS)([.-].*)?$", re.I)


def run(*args, **kw):
    return subprocess.run(args, cwd=ROOT, check=True, capture_output=True, text=True, **kw).stdout


def linked_modules(pkg):
    with tempfile.TemporaryDirectory() as d:
        binary = os.path.join(d, "bin")
        run("go", "build", "-o", binary, pkg)
        mods = []
        for line in run("go", "version", "-m", binary).splitlines():
            f = line.split()
            if len(f) >= 3 and f[0] == "dep":
                path, version = f[1], f[2]
                # A replaced module is listed on the following "=>" line.
                mods.append([path, version])
            elif len(f) >= 3 and f[0] == "=>" and mods:
                mods[-1] = [f[1], f[2]]
        return sorted(mods)


def module_dir(path, version):
    out = run("go", "mod", "download", "-json", f"{path}@{version}")
    return json.loads(out)["Dir"]


def licence_texts(directory):
    texts = []
    for name in sorted(os.listdir(directory)):
        full = os.path.join(directory, name)
        if os.path.isfile(full) and LICENSE_RE.match(name):
            with open(full, encoding="utf-8", errors="replace") as fh:
                texts.append((name, fh.read().strip()))
    return texts


def render(binary, pkg):
    goroot = run("go", "env", "GOROOT").strip()
    goversion = run("go", "env", "GOVERSION").strip()
    parts = [
        f"Third-party software linked into the {binary} binary ({pkg})",
        "Generated by scripts/go_licenses.py. Do not edit by hand.",
        "",
    ]
    stdlib = licence_texts(goroot)
    parts += ["=" * 78, f"The Go standard library ({goversion})", "=" * 78]
    parts += [t for _, t in stdlib] + [""]
    missing = []
    for path, version in linked_modules(pkg):
        texts = licence_texts(module_dir(path, version))
        if not texts:
            missing.append(path)
        parts += ["=" * 78, f"{path} {version}", "=" * 78]
        for name, text in texts:
            parts += [f"--- {name} ---", text, ""]
        if not texts:
            parts += ["(no licence file found in the module)", ""]
    return "\n".join(parts).rstrip() + "\n", missing


def main():
    check = "--check" in sys.argv[1:]
    os.makedirs(OUT_DIR, exist_ok=True)
    stale = []
    for binary, pkg in TARGETS.items():
        text, missing = render(binary, pkg)
        for m in missing:
            print(f"warning: {binary}: no licence file in module {m}", file=sys.stderr)
        path = os.path.join(OUT_DIR, f"{binary}-go.txt")
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if check:
            if current != text:
                stale.append(path)
        elif current != text:
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(text)
            print(f"wrote {os.path.relpath(path, ROOT)}")
    if stale:
        print("out of date (run python3 scripts/go_licenses.py): " + ", ".join(os.path.relpath(p, ROOT) for p in stale),
              file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
