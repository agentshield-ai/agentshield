// The native routes need a key and check roles like every other route;
// GET /api/v1/files/{digest} also takes the key as api_key (for <img src>).
func TestNativeAuth(t *testing.T) {
	e := newEnv(t, "k1")
	d := e.uploadFile([]byte("img"))
	e.key = ""
	for _, p := range []string{"/api/v1/spans/query", "/api/v1/objects/query", "/api/v1/feedback/query", "/api/v1/refs/read"} {
		if code, _ := e.raw(p, map[string]any{"project_id": pid}, nil); code != 401 {
			t.Fatalf("%s without a key -> %d", p, code)
		}
	}
	u := e.srv.URL + "/api/v1/files/" + d + "?" + url.Values{"project_id": {pid}}.Encode()
	if code, _ := httpGet(t, u); code != 401 {
		t.Fatalf("file without a key -> %d", code)
	}
	if code, body := httpGet(t, u+"&api_key=k1"); code != 200 || string(body) != "img" {
		t.Fatalf("file with api_key -> %d %s", code, body)
	}
	// The query key works for file reads only.
	if code, _ := httpGet(t, e.srv.URL+"/api/v1/objects/x?project_id="+pid+"&api_key=k1"); code != 401 {
		t.Fatalf("api_key on another route -> %d", code)
	}
}
